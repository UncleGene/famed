class DnaSyncError(ValueError):
    pass


_PROVIDER_MARKERS: dict[str, tuple[str, ...]] = {
    "23andme": (
        "# This data file generated by 23andMe",
        "# This data file is generated by 23andMe",
    ),
    "ancestrydna": ("#AncestryDNA",),
    "myheritage": ("# MyHeritage DNA raw data",),
    "genotek": ("Genotek",),
}

_MAX_HEADER_LINES = 30
_MAX_ESTIMATE_SCAN_ROWS = 100_000
DEFAULT_IMPUTED_QUALITY_FLOOR = 0.3
_ZIP_DNA_SUFFIXES = (".txt", ".csv", ".vcf", ".gz", ".vcf.gz")

_PROVIDER_LABELS: dict[str, str] = {
    "23andme": "23andMe",
    "ancestrydna": "AncestryDNA",
    "myheritage": "MyHeritage",
    "genotek": "Genotek",
    "nebula": "Nebula Genomics",
    "vcf": "VCF",
}


@dataclass(frozen=True)
class DnaFileDetection:
    provider: str
    confidence: float
    genome_build: str | None
    chip_version: str | None
    source_kind: str
    estimated_variant_count: int


@dataclass(frozen=True)
class DnaImportSummary:
    provider: str
    chip_version: str | None


def _open_text(path: Path) -> TextIO:
    if path.name.lower().endswith(".gz"):
        return gzip.open(path, "rt", encoding="utf-8", errors="replace", newline="")
    return path.open("r", encoding="utf-8", errors="replace", newline="")


def _looks_like_supported_dna_member(name: str) -> bool:
    lowered = name.lower()
    if lowered.startswith("__macosx/") or Path(name).name.startswith("._"):
        return False
    return lowered.endswith(_ZIP_DNA_SUFFIXES)


@contextmanager
def _readable_dna_source(path: Path) -> Generator[Path]:
    if path.suffix.lower() != ".zip":
        yield path
        return

    try:
        with zipfile.ZipFile(path) as archive:
            candidates = [
                info
                for info in archive.infolist()
                if not info.is_dir() and _looks_like_supported_dna_member(info.filename)
            ]
            if len(candidates) != 1:
                raise DnaSyncError(f"{path.name} must contain exactly one supported raw DNA file")

            member = candidates[0]
            with tempfile.TemporaryDirectory(prefix="famed-dna-") as tmp_dir:
                tmp_path = Path(tmp_dir) / Path(member.filename).name
                with archive.open(member) as src, tmp_path.open("wb") as dst:
                    shutil.copyfileobj(src, dst)
                yield tmp_path
    except zipfile.BadZipFile as exc:
        raise DnaSyncError(f"{path.name} is not a readable ZIP archive") from exc


def _read_header_lines(path: Path) -> list[str]:
    lines: list[str] = []
    with _open_text(path) as fh:
        for i, line in enumerate(fh):
            if i >= _MAX_HEADER_LINES:
                break
            lines.append(line.rstrip("\r\n"))
    return lines


def _estimate_variant_count(path: Path) -> int:
    try:
        with _open_text(path) as fh:
            count = 0
            for line in fh:
                if line.strip() and not line.startswith("#"):
                    count += 1
                    if count >= _MAX_ESTIMATE_SCAN_ROWS:
                        return count
            return count
    except OSError:
        return 0


def _detect_genome_build(lines: list[str]) -> str | None:
    text = "\n".join(lines).lower()
    if any(marker in text for marker in ("grch38", "hg38", "b38")):
        return "GRCh38"
    if any(marker in text for marker in ("grch37", "hg19", "b37")):
        return "GRCh37"
    return None


def _provider_label(provider: str) -> str:
    return _PROVIDER_LABELS.get(provider, provider)


def provider_label(provider: str) -> str:
    """Public wrapper for user-facing provider labels."""
    return _provider_label(provider)


def _matches_provider_marker(line: str, markers: tuple[str, ...]) -> bool:
    return any(line.startswith(marker) for marker in markers)


def detect_dna_file(path: Path) -> DnaFileDetection | None:
    """Return provider/format metadata without importing variant rows."""
    try:
        with _readable_dna_source(path) as readable_path:
            lines = _read_header_lines(readable_path)

            genome_build = _detect_genome_build(lines)
            lower_name = readable_path.name.lower()
            for provider, markers in _PROVIDER_MARKERS.items():
                if any(_matches_provider_marker(line, markers) for line in lines):
                    return DnaFileDetection(
                        provider=provider,
                        confidence=1.0,
                        genome_build=genome_build,
                        chip_version=extract_chip_version(readable_path),
                        source_kind="genotyped",
                        estimated_variant_count=_estimate_variant_count(readable_path),
                    )

            is_vcf = any(line.startswith("##fileformat=VCF") for line in lines)
            if is_vcf or lower_name.endswith((".vcf", ".vcf.gz")):
                provider = "nebula" if any("nebula" in line.lower() for line in lines) else "vcf"
                source_kind = "imputed" if _vcf_header_suggests_imputed(lines) else "genotyped"
                return DnaFileDetection(
                    provider=provider,
                    confidence=0.95 if is_vcf else 0.3,
                    genome_build=genome_build,
                    chip_version=None,
                    source_kind=source_kind,
                    estimated_variant_count=_estimate_variant_count(readable_path),
                )
    except (OSError, DnaSyncError):
        return None

    return None


def detect_provider(path: Path) -> str | None:
    """Return the detected DNA provider id, or None when unrecognised."""
    detection = detect_dna_file(path)
    return detection.provider if detection else None


def extract_chip_version(path: Path) -> str | None:
    """Extract chip/array version from header comments (e.g. 'v5')."""
    try:
        with _readable_dna_source(path) as readable_path:
            for line in _read_header_lines(readable_path):
                if not line.startswith("#"):
                    break
                m = re.search(r"\bv(\d+)\b", line, re.IGNORECASE)
                if m:
                    return f"v{m.group(1)}"
            filename_match = re.search(
                r"(?:^|[^A-Za-z0-9])v(\d+)(?:[^A-Za-z0-9]|$)",
                readable_path.name,
                re.IGNORECASE,
            )
            if filename_match:
                return f"v{filename_match.group(1)}"
    except (OSError, DnaSyncError):
        pass
    return None


def _genotype_row_id(person_id: str, source_path: str, rsid: str) -> str:
    raw = f"{person_id}|{source_path}|{rsid}".encode()
    return hashlib.sha1(raw).hexdigest()


def _find_dna_header(fh: Any) -> tuple[list[str], str] | tuple[None, None]:
    """Scan *fh* for the column header line; return (fieldnames, delimiter) or (None, None).

    Detects both tab-delimited (23andMe, AncestryDNA) and comma-delimited
    (MyHeritage) headers.  The header may or may not start with '#'.
    After this function returns, *fh* is positioned immediately after the
    header line so the caller can stream data rows directly.
    """
    for line in fh:
        candidate = line.rstrip("\r\n").lstrip("# ")
        lower = candidate.lower()
        if "rsid" not in lower or "chromosome" not in lower:
            continue
        if "\t" in candidate:
            fieldnames = candidate.split("\t")
            lowered = {field.strip().lower() for field in fieldnames}
            if {"rsid", "chromosome", "position"} <= lowered:
                return fieldnames, "\t"
        if "," in candidate:
            fieldnames = next(csv.reader([candidate]))
            lowered = {field.strip().lower() for field in fieldnames}
            if {"rsid", "chromosome", "position"} <= lowered:
                return fieldnames, ","
    return None, None


def _vcf_header_suggests_imputed(lines: list[str]) -> bool:
    text = "\n".join(lines).lower()
    return any(marker in text for marker in ("imput", "r2", "dr2", "ar2"))


def _extract_vcf_quality(info_field: str) -> float | None:
    for key in ("R2", "DR2", "AR2"):
        match = re.search(rf"(?:^|;){key}=([0-9.]+)(?:;|$)", info_field)
        if not match:
            continue
        try:
            return float(match.group(1))
        except ValueError:
            return None
    return None


def _parse_vcf_variants(
    path: Path,
    provider: str,
    person_id: str,
    source_path: str,
    *,
    min_quality: float,
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    header_lines = _read_header_lines(path)
    genome_build = _detect_genome_build(header_lines)
    source_kind = "imputed" if _vcf_header_suggests_imputed(header_lines) else "genotyped"
    try:
        with _open_text(path) as fh:
            for line in fh:
                if not line.strip() or line.startswith("#"):
                    continue
                parts = line.rstrip("\r\n").split("\t")
                if len(parts) < 10:
                    continue
                chromosome = parts[0].removeprefix("chr")
                try:
                    position: int | None = int(parts[1])
                except ValueError:
                    position = None
                rsid = parts[2]
                if not rsid or rsid == ".":
                    continue
                ref = parts[3]
                alt = parts[4]
                if "," in alt:
                    continue
                quality = _extract_vcf_quality(parts[7])
                row_source_kind = "imputed" if quality is not None else source_kind
                if row_source_kind == "imputed" and quality is not None and quality < min_quality:
                    continue
                format_keys = parts[8].split(":")
                sample_values = parts[9].split(":")
                gt_idx = format_keys.index("GT") if "GT" in format_keys else 0
                if gt_idx >= len(sample_values):
                    continue
                gt_raw = sample_values[gt_idx]
                if not gt_raw or gt_raw == "./.":
                    allele1, allele2 = "-", "-"
                else:
                    alleles = [ref] + alt.split(",")
                    try:
                        indices = [
                            int(value) for value in re.split(r"[/|]", gt_raw) if value != "."
                        ]
                    except ValueError:
                        continue
                    if len(indices) < 2 or any(index >= len(alleles) for index in indices):
                        continue
                    allele1, allele2 = sorted((alleles[indices[0]], alleles[indices[1]]))
                rows.append(
                    {
                        "id": _genotype_row_id(person_id, source_path, rsid),
                        "person_id": person_id,
                        "rsid": rsid,
                        "chromosome": chromosome,
                        "position": position,
                        "allele1": allele1,
                        "allele2": allele2,
                        "provider": provider,
                        "source_path": source_path,
                        "source_kind": row_source_kind,
                        "quality": quality,
                        "genome_build": genome_build,
                    }
                )
    except OSError as exc:
        raise DnaSyncError(f"failed to parse {path.name}: {exc}") from exc

    return rows


def parse_dna_variants(
    path: Path,
    provider: str,
    person_id: str,
    source_path: str,
    *,
    min_quality: float = DEFAULT_IMPUTED_QUALITY_FLOOR,
) -> list[dict[str, Any]]:
    """Parse a supported raw DNA file into normalised genotype rows.

    DTC exports use either a single ``genotype``/``result`` column or separate
    allele columns. VCF exports use GT over REF/ALT alleles.
    """
    if path.suffix.lower() == ".zip":
        with _readable_dna_source(path) as readable_path:
            return parse_dna_variants(
                readable_path,
                provider,
                person_id,
                source_path,
                min_quality=min_quality,
            )

    if provider in {"vcf", "nebula"}:
        return _parse_vcf_variants(
            path,
            provider,
            person_id,
            source_path,
            min_quality=min_quality,
        )

    rows: list[dict[str, Any]] = []
    try:
        genome_build = _detect_genome_build(_read_header_lines(path))
        with _open_text(path) as fh:
            fieldnames, delimiter = _find_dna_header(fh)
            if not fieldnames or not delimiter:
                raise DnaSyncError(f"no column header (rsid) found in {path.name}")

            reader = csv.DictReader(fh, fieldnames=fieldnames, delimiter=delimiter)
            for raw_row in reader:
                row = {(k or "").strip().lower(): (v or "").strip() for k, v in raw_row.items()}
                rsid = row.get("rsid", "")
                if not rsid or rsid.startswith("#"):
                    continue

                chromosome = row.get("chromosome", "") or row.get("chrom", "")
                try:
                    position: int | None = int(row.get("position", ""))
                except (ValueError, TypeError):
                    position = None

                if provider in ("23andme", "myheritage", "genotek"):
                    # Both use a single genotype/result column (e.g. "AA", "--")
                    genotype = row.get("genotype") or row.get("result", "--")
                    if len(genotype) >= 2:
                        allele1, allele2 = genotype[0], genotype[1]
                    else:
                        allele1, allele2 = "-", "-"
                else:  # ancestrydna
                    allele1 = row.get("allele1", "-") or "-"
                    allele2 = row.get("allele2", "-") or "-"

                rows.append(
                    {
                        "id": _genotype_row_id(person_id, source_path, rsid),
                        "person_id": person_id,
                        "rsid": rsid,
                        "chromosome": chromosome,
                        "position": position,
                        "allele1": allele1,
                        "allele2": allele2,
                        "provider": provider,
                        "source_path": source_path,
                        "source_kind": "genotyped",
                        "quality": None,
                        "genome_build": genome_build,
                    }
                )
    except (OSError, csv.Error) as exc:
        raise DnaSyncError(f"failed to parse {path.name}: {exc}") from exc

    return rows


def dna_file_checksum(path: Path) -> str:
    """Return SHA-256 hex digest of file contents."""
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def is_already_imported(conn: sqlite3.Connection, person_id: str, checksum: str) -> bool:
    """Return True when this exact file has already been imported for person_id."""
    row = conn.execute(
        "SELECT 1 FROM dna_imports WHERE person_id = ? AND file_checksum = ?",
        (person_id, checksum),
    ).fetchone()
    return row is not None


def replace_genotypes_for_source_path(
    conn: sqlite3.Connection,
    source_path: str,
    rows: list[dict[str, Any]],
) -> int:
    """Delete existing genotype rows for source_path and bulk-insert new ones."""
    _ensure_genotype_provenance_columns(conn)
    conn.execute("DELETE FROM genotypes WHERE source_path = ?", (source_path,))
    inserted = 0
    direct_rows: list[dict[str, Any]] = []
    for row in rows:
        source_kind = str(row.get("source_kind") or "genotyped")
        if source_kind == "imputed":
            direct = conn.execute(
                """
                SELECT 1 FROM genotypes
                WHERE person_id = ? AND rsid = ? AND source_kind = 'genotyped'
                LIMIT 1
                """,
                (row["person_id"], row["rsid"]),
            ).fetchone()
            if direct:
                continue
        else:
            direct_rows.append(row)
            continue
        _insert_genotype_row(conn, row, source_kind)
        inserted += 1
    if direct_rows:
        has_imputed_rows = conn.execute(
            "SELECT 1 FROM genotypes WHERE source_kind = 'imputed' LIMIT 1"
        ).fetchone()
        if has_imputed_rows:
            conn.executemany(
                """
                DELETE FROM genotypes
                WHERE person_id = ? AND rsid = ? AND source_kind = 'imputed'
                """,
                ((row["person_id"], row["rsid"]) for row in direct_rows),
            )
        conn.executemany(
            _GENOTYPE_INSERT_SQL,
            (_genotype_insert_values(row, "genotyped") for row in direct_rows),
        )
        inserted += len(direct_rows)
    return inserted


_GENOTYPE_INSERT_SQL = """INSERT OR REPLACE INTO genotypes
   (id, person_id, rsid, chromosome, position,
    allele1, allele2, provider, source_path,
    source_kind, quality, genome_build)
   VALUES (:id, :person_id, :rsid, :chromosome, :position,
           :allele1, :allele2, :provider, :source_path,
           :source_kind, :quality, :genome_build)"""


def _genotype_insert_values(row: dict[str, Any], source_kind: str) -> dict[str, Any]:
    return {
        **row,
        "source_kind": source_kind,
        "quality": row.get("quality"),
        "genome_build": row.get("genome_build"),
    }


def _insert_genotype_row(
    conn: sqlite3.Connection,
    row: dict[str, Any],
    source_kind: str,
) -> None:
    conn.execute(_GENOTYPE_INSERT_SQL, _genotype_insert_values(row, source_kind))


def _ensure_genotype_provenance_columns(conn: sqlite3.Connection) -> None:
    columns = {row[1] for row in conn.execute("PRAGMA table_info(genotypes)")}
    if "source_kind" not in columns:
        conn.execute(
            "ALTER TABLE genotypes ADD COLUMN source_kind TEXT NOT NULL DEFAULT 'genotyped'"
        )
    if "quality" not in columns:
        conn.execute("ALTER TABLE genotypes ADD COLUMN quality REAL")
    if "genome_build" not in columns:
        conn.execute("ALTER TABLE genotypes ADD COLUMN genome_build TEXT")


def upsert_dna_import(
    conn: sqlite3.Connection,
    person_id: str,
    provider: str,
    checksum: str,
    source_path: str,
    variant_count: int,
    chip_version: str | None,
    *,
    imported_at: str | None = None,
) -> None:
    import_id = hashlib.sha1(f"{person_id}|{source_path}".encode()).hexdigest()
    conn.execute(
        """INSERT OR REPLACE INTO dna_imports
           (id, person_id, provider, file_checksum, source_path,
            variant_count, chip_version, imported_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
        (
            import_id,
            person_id,
            provider,
            checksum,
            source_path,
            variant_count,
            chip_version,
            imported_at or datetime.now(UTC).isoformat(),
        ),
    )


def render_dna_vault_note(
    person_id: str,
    provider: str,
    chip_version: str | None,
    source_path: str,
    source_file_name: str,
    variant_count: int,
    *,
    imported_at: str | None = None,
) -> str:
    front_matter: dict[str, Any] = {
        "person_id": person_id,
        "record_type": "dna_profile",
        "provider": provider,
        "chip_version": chip_version,
        "source_path": source_path,
        "source_file_name": source_file_name,
        "variant_count": variant_count,
        "imported_at": (imported_at or datetime.now(UTC).isoformat())[:10],
    }
    yaml_block = yaml.safe_dump(front_matter, sort_keys=False, allow_unicode=False).strip()
    chip_label = f" ({chip_version})" if chip_version else ""
    return (
        f"---\n{yaml_block}\n---\n\n"
        f"# DNA Profile\n\n"
        f"[[{person_id}|← {person_id}]]\n\n"
        f"**Provider:** {_provider_label(provider)}{chip_label}  \n"
        f"**Variants:** {variant_count:,}  \n"
        f"**Source:** `{source_path}`\n"
    )


def persist_dna_source(
    conn: sqlite3.Connection,
    vault_root: Path,
    *,
    person_id: str,
    source_path: Path,
    canonical_source_path: str,
    source_file_name: str,
    note_name: str,
    imported_at: str | None = None,
    provider: str | None = None,
) -> int:
    """Persist one retained DNA source without moving it or committing.

    Callers own transaction boundaries, retained-source placement, and
    dependent-report refreshes.
    """
    detected_provider = provider or detect_provider(source_path)
    if detected_provider is None:
        raise DnaSyncError(
            f"DNA format not recognised for {source_path.name}; expected 23andMe, "
            "AncestryDNA, MyHeritage, Genotek, or VCF/VCF.GZ"
        )

    checksum = dna_file_checksum(source_path)
    chip_version = extract_chip_version(source_path)
    variants = parse_dna_variants(
        source_path,
        detected_provider,
        person_id,
        canonical_source_path,
    )
    if not variants:
        raise DnaSyncError(f"no valid variant rows parsed from {source_path.name}")

    replace_genotypes_for_source_path(conn, canonical_source_path, variants)
    upsert_dna_import(
        conn,
        person_id,
        detected_provider,
        checksum,
        canonical_source_path,
        len(variants),
        chip_version,
        imported_at=imported_at,
    )

    genes_dir = vault_root / "Records" / person_id / "Genes"
    genes_dir.mkdir(parents=True, exist_ok=True)
    note_path = genes_dir / note_name
    note_path.write_text(
        render_dna_vault_note(
            person_id,
            detected_provider,
            chip_version,
            canonical_source_path,
            source_file_name,
            len(variants),
            imported_at=imported_at,
        ),
        encoding="utf-8",
    )
    write_category_index_note(
        genes_dir,
        person_id,
        "Genes",
        note_label="DNA profile",
        display_name=load_person_display_name(vault_root, person_id),
    )
    return len(variants)


def load_latest_dna_import_summary(
    conn: sqlite3.Connection,
    person_id: str,
) -> DnaImportSummary | None:
    row = conn.execute(
        """
        SELECT provider, chip_version
        FROM dna_imports
        WHERE person_id = ?
        ORDER BY imported_at DESC
        LIMIT 1
        """,
        (person_id,),
    ).fetchone()
    if row is None:
        return None
    return DnaImportSummary(
        provider=str(row[0]),
        chip_version=str(row[1]) if row[1] else None,
    )
