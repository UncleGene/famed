def test_replace_genotypes_idempotent() -> None:
    conn = _dna_conn()
    rows = [
        {
            "id": "id1",
            "person_id": "dummy_alice",
            "rsid": "rs123",
            "chromosome": "1",
            "position": 100,
            "allele1": "A",
            "allele2": "G",
            "provider": "23andme",
            "source_path": "src.txt",
        }
    ]
    replace_genotypes_for_source_path(conn, "src.txt", rows)
    replace_genotypes_for_source_path(conn, "src.txt", rows)
    count = conn.execute("SELECT COUNT(*) FROM genotypes").fetchone()[0]
    assert count == 1


def test_replace_genotypes_clears_old_rows() -> None:
    conn = _dna_conn()
    old = [
        {
            "id": "old1",
            "person_id": "dummy_alice",
            "rsid": "rs999",
            "chromosome": "2",
            "position": 200,
            "allele1": "C",
            "allele2": "T",
            "provider": "23andme",
            "source_path": "src.txt",
        }
    ]
    new = [
        {
            "id": "new1",
            "person_id": "dummy_alice",
            "rsid": "rs123",
            "chromosome": "1",
            "position": 100,
            "allele1": "A",
            "allele2": "G",
            "provider": "23andme",
            "source_path": "src.txt",
        }
    ]
    replace_genotypes_for_source_path(conn, "src.txt", old)
    replace_genotypes_for_source_path(conn, "src.txt", new)
    rsids = [r[0] for r in conn.execute("SELECT rsid FROM genotypes").fetchall()]
    assert rsids == ["rs123"]


